def mode_run(countries, precomputed, args):
    os.makedirs(OUTPUT_DIR_FORECAST, exist_ok=True)
    params = build_model_params(
        input_chunk_length=(args.input_chunk_length
                            or TRANSFORMER_KWARGS["input_chunk_length"]),
        num_encoder_layers=(args.num_encoder_layers
                            or TRANSFORMER_KWARGS["num_encoder_layers"]),
        num_decoder_layers=(args.num_decoder_layers
                            or TRANSFORMER_KWARGS["num_decoder_layers"]),
        dropout=(args.dropout if args.dropout is not None
                 else TRANSFORMER_KWARGS["dropout"]),
        n_epochs=args.n_epochs or TRANSFORMER_KWARGS["n_epochs"],
    )
    print(f"\n{'='*70}")
    print("Direct Run Mode")
    for k, v in sorted(params.items()):
        print(f"    {k}: {v}")
    print(f"  Output dir: {OUTPUT_DIR_FORECAST}")
    print(f"{'='*70}\n")
    final_wis = run_one_backtest(
        countries, precomputed, params,
        verbose=True, save_forecasts=True, forecast_dir=OUTPUT_DIR_FORECAST)
    print(f"\nFinal WIS = {final_wis:.4f}")
    print(f"R evaluation: OUTPUT_DIR <- \"{OUTPUT_DIR_FORECAST}\"")


