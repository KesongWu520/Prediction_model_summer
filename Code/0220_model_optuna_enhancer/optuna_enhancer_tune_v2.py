def run_one_backtest(countries, precomputed, model_params,
                     verbose=False, save_forecasts=False, forecast_dir=None):
    """Run full backtest. Returns mean_wis (float)."""

    input_chunk_length = model_params["input_chunk_length"]
    all_wis = []
    all_outputs = []
    all_round_losses = {}

    for target in precomputed:
        data = precomputed[target]
        log_series = data["log_series"]
        raw_series = data["raw_series"]
        full_cov = data["full_cov"]
        n_rounds = data["n_rounds"]
        safe_target = target.replace(" ", "_")
        target_wis = []
        target_losses = []

        for round_idx in range(n_rounds):
            offset = round_idx * STEP_WEEKS
            train_list, meta = [], []
            cov_train_list, cov_full_list = [], []

            for c in countries:
                train_ts_log, _, forecast_date = split_train_test_by_offset(
                    log_series[c], TEST_WEEKS, offset, MIN_TRAIN_WEEKS)
                if train_ts_log is None:
                    continue
                if len(train_ts_log) < input_chunk_length + TEST_WEEKS:
                    continue
                _, test_ts_raw, _ = split_train_test_by_offset(
                    raw_series[c], TEST_WEEKS, offset, MIN_TRAIN_WEEKS)
                train_list.append(train_ts_log)
                meta.append((c, forecast_date, test_ts_raw))
                n = len(log_series[c])
                test_end = n - offset
                train_end = test_end - TEST_WEEKS
                cov_train_list.append(full_cov[c][:train_end])
                cov_full_list.append(full_cov[c][:test_end])

            if not train_list:
                continue

            y_scaler = Scaler()
            train_scaled = y_scaler.fit_transform(train_list)
            x_scaler = Scaler()
            cov_train_scaled = x_scaler.fit_transform(cov_train_list)
            cov_full_scaled = x_scaler.transform(cov_full_list)

            try:
                loss_logger = LossLogger() if verbose else None
                pl_kwargs = {"callbacks": [loss_logger]} if verbose else {}

                model = TransformerModel(
                    input_chunk_length=model_params["input_chunk_length"],
                    output_chunk_length=TEST_WEEKS,
                    d_model=model_params["d_model"],
                    nhead=model_params["nhead"],
                    num_encoder_layers=model_params["num_encoder_layers"],
                    num_decoder_layers=model_params["num_decoder_layers"],
                    dim_feedforward=model_params["dim_feedforward"],
                    batch_size=model_params["batch_size"],
                    n_epochs=model_params["n_epochs"],
                    dropout=model_params["dropout"],
                    activation=model_params["activation"],
                    random_state=42,
                    save_checkpoints=False,
                    force_reset=True,
                    log_tensorboard=False,
                    optimizer_kwargs={"lr": 1e-3},
                    lr_scheduler_cls=torch.optim.lr_scheduler.ReduceLROnPlateau,
                    lr_scheduler_kwargs={
                        "patience": 10, "factor": 0.5,
                        "min_lr": 1e-5, "monitor": "train_loss",
                    },
                    likelihood=QuantileRegression(quantiles=QUANTILES),
                    model_name=f"bt_r{round_idx}_{safe_target}",
                    pl_trainer_kwargs=pl_kwargs,
                )

                model.fit(series=train_scaled,
                          past_covariates=cov_train_scaled, verbose=False)

                if verbose and loss_logger and loss_logger.train_epoch_losses:
                    target_losses.append(loss_logger.train_epoch_losses)

                preds_scaled = []
                for i in range(len(meta)):
                    preds_scaled.append(
                        model.predict(
                            n=TEST_WEEKS, series=train_scaled[i],
                            past_covariates=cov_full_scaled[i],
                            num_samples=PRED_NUM_SAMPLES))

                preds_log = y_scaler.inverse_transform(preds_scaled)
                preds_original = [inverse_log_transform_samples(p) for p in preds_log]

                for i, (country, forecast_date, test_ts_raw) in enumerate(meta):
                    y_true = test_ts_raw.values().flatten()
                    try:
                        q_dict = forecast_to_qdict(preds_original[i])
                        wis = evaluate_wis(y_true, q_dict)
                        if not np.isnan(wis):
                            target_wis.append(wis)
                    except Exception:
                        pass

                    if save_forecasts:
                        try:
                            out_df = generate_output(
                                forecast_date, target, country,
                                preds_original[i])
                            out_df["backtest_round"] = round_idx + 1
                            out_df["known_weeks"] = len(train_list[i])
                            all_outputs.append(out_df)
                            safe_c = country.replace(" ", "_")
                            fname = (f"forecast_{safe_c}_{safe_target}_"
                                     f"{forecast_date.strftime('%Y-%m-%d')}.csv")
                            out_df.to_csv(
                                os.path.join(forecast_dir, fname), index=False)
                        except Exception as e:
                            if verbose:
                                print(f"      {country}: output error - {e}")

            except Exception as e:
                if verbose:
                    print(f"    Round {round_idx}: error - {e}")
                continue

            if verbose and (round_idx == 0 or round_idx == n_rounds - 1
                            or (round_idx + 1) % 10 == 0):
                mu = np.mean(target_wis) if target_wis else float('nan')
                print(f"    Round {round_idx+1}/{n_rounds}: "
                      f"train={len(train_list[0])}w, running WIS={mu:.4f}")

        if target_wis:
            all_wis.extend(target_wis)
            if verbose:
                print(f"  {target}: mean WIS = {np.mean(target_wis):.4f} "
                      f"({len(target_wis)} evals)")

        if verbose and target_losses:
            all_round_losses[target] = target_losses

    mean_wis = np.mean(all_wis) if all_wis else float("inf")

    if save_forecasts and all_outputs:
        combined = pd.concat(all_outputs, ignore_index=True)
        combined.to_csv(os.path.join(forecast_dir, "all_forecasts.csv"),
                        index=False)
        if verbose:
            print(f"\n  Saved: all_forecasts.csv ({len(combined)} rows)")

    if verbose and all_round_losses and forecast_dir:
        for tgt, ll in all_round_losses.items():
            for ri, ls in enumerate(ll):
                if ri == 0 or ri == len(ll) - 1 or (ri + 1) % 10 == 0:
                    plot_loss_curve(ls, tgt, ri, forecast_dir)
            plot_loss_summary(ll, tgt, forecast_dir)

    return mean_wis


