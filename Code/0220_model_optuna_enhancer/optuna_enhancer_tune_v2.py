# Mode: tune
# ============================================================

def mode_tune(countries, precomputed):
    import optuna
    from optuna.samplers import TPESampler

    os.makedirs(OUTPUT_DIR_TUNE, exist_ok=True)
    os.makedirs(OUTPUT_DIR_FORECAST, exist_ok=True)

    print(f"\n{'='*70}")
    print("Phase 1: Optuna Hyperparameter Tuning")
    print(f"  Trials: {N_TRIALS}")
    print(f"  Tuning: input_chunk_length, encoder/decoder layers, dropout, n_epochs")
    print(f"  Fixed:  d_model={FIXED_PARAMS['d_model']}, "
          f"nhead={FIXED_PARAMS['nhead']}, "
          f"ff={FIXED_PARAMS['dim_feedforward']}, "
          f"batch={FIXED_PARAMS['batch_size']}, "
          f"{FIXED_PARAMS['activation']}")
    print(f"{'='*70}\n")

    def objective(trial):
        icl = trial.suggest_categorical("input_chunk_length", [13, 20, 26, 33, 39, 52])
        enc = trial.suggest_int("num_encoder_layers", 1, 3)
        dec = trial.suggest_int("num_decoder_layers", 1, 3)
        dr = trial.suggest_float("dropout", 0.05, 0.3, step=0.05)
        ne = trial.suggest_categorical("n_epochs", [50, 75, 100, 125, 150])
        params = build_model_params(icl, enc, dec, dr, ne)
        print(f"\n  Trial {trial.number}: icl={icl}, enc={enc}, dec={dec}, "
              f"drop={dr:.2f}, epochs={ne}")
        mean_wis = run_one_backtest(
            countries, precomputed, params, verbose=False, save_forecasts=False)
        print(f"  Trial {trial.number} RESULT: mean WIS = {mean_wis:.4f}")
        return mean_wis

    study = optuna.create_study(
        study_name="transformer_hpo", direction="minimize",
        sampler=TPESampler(seed=42))
    study.enqueue_trial({
        "input_chunk_length": 26, "num_encoder_layers": 2,
        "num_decoder_layers": 2, "dropout": 0.1, "n_epochs": 100,
    })
    study.optimize(objective, n_trials=N_TRIALS, show_progress_bar=True)

    best = study.best_trial
    bl = study.trials[0].value
    print(f"\n{'='*70}")
    print("Phase 1 Complete!")
    print(f"  Baseline: WIS = {bl:.4f}")
    print(f"  Best (Trial {best.number}): WIS = {best.value:.4f}")
    if bl and best.value < bl:
        print(f"  Improvement: {(bl - best.value) / bl * 100:.2f}%")
    for k, v in sorted(best.params.items()):
        print(f"    {k}: {v}")

    trials_df = study.trials_dataframe()
    trials_df.to_csv(os.path.join(OUTPUT_DIR_TUNE, "optuna_trials.csv"), index=False)
    pd.DataFrame([{**best.params, "wis": best.value}]).to_csv(
        os.path.join(OUTPUT_DIR_TUNE, "best_params.csv"), index=False)

    # Phase 2
    bp = best.params
    best_mp = build_model_params(
        bp["input_chunk_length"], bp["num_encoder_layers"],
        bp["num_decoder_layers"], bp["dropout"], bp["n_epochs"])
    print(f"\n{'='*70}")
    print("Phase 2: Full backtest + R output")
    print(f"{'='*70}\n")
    final_wis = run_one_backtest(
        countries, precomputed, best_mp,
        verbose=True, save_forecasts=True, forecast_dir=OUTPUT_DIR_FORECAST)
    print(f"\nFinal WIS = {final_wis:.4f}")
    print(f"R evaluation: OUTPUT_DIR <- \"{OUTPUT_DIR_FORECAST}\"")


