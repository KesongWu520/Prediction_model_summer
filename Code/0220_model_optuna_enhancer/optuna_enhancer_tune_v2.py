def main():
    parser = argparse.ArgumentParser(
        description="Enhanced Transformer Forecasting",
        formatter_class=argparse.RawTextHelpFormatter)
    parser.add_argument("mode", choices=["tune", "run"])
    parser.add_argument("--input_chunk_length", type=int, default=None)
    parser.add_argument("--num_encoder_layers", type=int, default=None)
    parser.add_argument("--num_decoder_layers", type=int, default=None)
    parser.add_argument("--n_epochs", type=int, default=None)
    parser.add_argument("--dropout", type=float, default=None)
    args = parser.parse_args()
    countries, precomputed = preload_data()
    if args.mode == "tune":
        mode_tune(countries, precomputed)
    else:
        mode_run(countries, precomputed, args)


if __name__ == "__main__":
    main()
