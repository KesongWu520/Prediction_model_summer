def log_transform_series(ts):
    vals = ts.all_values(copy=True)
    vals = np.log1p(np.clip(vals, 0, None))
    times = ts.time_index
    if vals.shape[2] == 1:
        return TimeSeries.from_times_and_values(
            times=times, values=vals[:, :, 0],
            columns=ts.components.tolist(),
            fill_missing_dates=False)
    return ts.with_values(vals)


def inverse_log_transform_samples(ts):
    vals = ts.all_values(copy=True)
    vals = np.expm1(vals)
    vals = np.clip(vals, a_min=0, a_max=None)
    return ts.with_values(vals)


